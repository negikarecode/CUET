/**
 * Common question translation patterns:
 * Automatically translates standardized NTA question stems and option phrasing into the chosen language.
 */
export function translateNTAQuestionStem(text: string, langCode: string): string {
  if (!text || langCode === "en") return text;
  const dict = translations[langCode] || translations.en;
  if (!dict) return text;

  let result = text;

  // Stems & Instructions
  if (dict.chooseCorrectAnswer) {
    result = result.replace(/Choose the correct answer from the options given below:?/gi, dict.chooseCorrectAnswer);
  }
  if (dict.inLightOfAbove) {
    result = result.replace(/In the light of the above statements, choose the (most appropriate|correct) answer from the options given below:?/gi, dict.inLightOfAbove);
  }
  if (dict.givenTwoStatements) {
    result = result.replace(/Given below are two statements:?/gi, dict.givenTwoStatements);
  }
  if (dict.considerStatements) {
    result = result.replace(/Consider the following statements:?/gi, dict.considerStatements);
  }
  if (dict.statementI) {
    result = result.replace(/Statement[- ]I:?/gi, dict.statementI);
  }
  if (dict.statementII) {
    result = result.replace(/Statement[- ]II:?/gi, dict.statementII);
  }
  if (dict.assertionA) {
    result = result.replace(/Assertion\s*\(?A\)?:\s*/gi, dict.assertionA + " ");
  }
  if (dict.reasonR) {
    result = result.replace(/Reason\s*\(?R\)?:\s*/gi, dict.reasonR + " ");
  }
  if (dict.matchList) {
    result = result.replace(/Match List-?I with List-?II:?/gi, dict.matchList);
  }
  if (dict.identifyCorrect) {
    result = result.replace(/identify the correct statement\(s\):?/gi, dict.identifyCorrect);
  }
  if (dict.identifyIncorrect) {
    result = result.replace(/identify the (INCORRECT|incorrect) statement\(s\):?/gi, dict.identifyIncorrect);
  }
  if (dict.whichOfFollowing) {
    result = result.replace(/Which of the following (statements? )?is (correct|true)\??/gi, dict.whichOfFollowing);
  }
  if (dict.whichOfFollowingNot) {
    result = result.replace(/Which of the following (statements? )?is (NOT correct|incorrect|false)\??/gi, dict.whichOfFollowingNot);
  }

  // Assertion / Reason Options
  if (dict.bothTrueAndExplanation) {
    result = result.replace(/Both \(A\) and \(R\) are true and \(R\) is the correct explanation of \(A\)/gi, dict.bothTrueAndExplanation);
  }
  if (dict.bothTrueNotExplanation) {
    result = result.replace(/Both \(A\) and \(R\) are true but \(R\) is NOT the correct explanation of \(A\)/gi, dict.bothTrueNotExplanation);
  }
  if (dict.aIsTrueRIsFalse) {
    result = result.replace(/\(A\) is true but \(R\) is false/gi, dict.aIsTrueRIsFalse);
  }
  if (dict.aIsFalseRIsTrue) {
    result = result.replace(/\(A\) is false but \(R\) is true/gi, dict.aIsFalseRIsTrue);
  }

  // Statements Options
  if (dict.bothStatementsCorrect) {
    result = result.replace(/Both Statement I and Statement II are (correct|true)/gi, dict.bothStatementsCorrect);
  }
  if (dict.bothStatementsIncorrect) {
    result = result.replace(/Both Statement I and Statement II are (incorrect|false)/gi, dict.bothStatementsIncorrect);
  }
  if (dict.statementICorrectOnly) {
    result = result.replace(/Statement I is (correct|true) but Statement II is (incorrect|false)/gi, dict.statementICorrectOnly);
  }
  if (dict.statementIIncorrectOnly) {
    result = result.replace(/Statement I is (incorrect|false) but Statement II is (correct|true)/gi, dict.statementIIncorrectOnly);
  }

  // Standard Combination Options
  if (dict.bAndDOnly) {
    result = result.replace(/\(?B\)? and \(?D\)? only/gi, dict.bAndDOnly);
  }
  if (dict.aAndCOnly) {
    result = result.replace(/\(?A\)? and \(?C\)? only/gi, dict.aAndCOnly);
  }
  if (dict.aAndBOnly) {
    result = result.replace(/\(?A\)? and \(?B\)? only/gi, dict.aAndBOnly);
  }
  if (dict.aBdOnly) {
    result = result.replace(/\(?A\)?, \(?B\)? and \(?D\)? only/gi, dict.aBdOnly);
  }
  if (dict.aBcOnly) {
    result = result.replace(/\(?A\)?, \(?B\)? and \(?C\)? only/gi, dict.aBcOnly);
  }
  if (dict.onlyA) {
    result = result.replace(/\(?A\)? only/gi, dict.onlyA);
  }
  if (dict.onlyB) {
    result = result.replace(/\(?B\)? only/gi, dict.onlyB);
  }
  if (dict.onlyC) {
    result = result.replace(/\(?C\)? only/gi, dict.onlyC);
  }
  if (dict.onlyD) {
    result = result.replace(/\(?D\)? only/gi, dict.onlyD);
  }
  if (dict.allAbove) {
    result = result.replace(/All of the above/gi, dict.allAbove);
  }
  if (dict.noneAbove) {
    result = result.replace(/None of the above/gi, dict.noneAbove);
  }

  return result;
}

