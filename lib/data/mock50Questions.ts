interface RawQuestion {
  questionNumber: number;
  questionId?: string;
  conceptId?: string;
  chapter: string;
  topic: string;
  questionText: string;
  hasDiagram?: boolean;
  diagramDescription?: string | null;
  options: {
    id: "A" | "B" | "C" | "D";
    text: string;
    isCorrect?: boolean;
    misconception?: {
      type: string;
      description: string;
    } | null;
    studentSelectionTrap?: string | null;
    mistakeAnalysis?: string;
  }[];
  correctOption: "A" | "B" | "C" | "D";
  detailedSolution: string;
  solution?: {
    quick: string;
    concept: string;
    detailed: string;
  };
  questionType?: any;
  difficulty?: number;
  estimatedTimeSeconds?: number;
  formula?: string;
  keyConcept?: string;
  tags?: string[];
  qualityScore?: number;
}

function mapQuestionsFromDataset(
  testId: string,
  subjectId: string,
  sourceLabel: string,
  notesPrefix: string,
  data: RawQuestion[]
): Question[] {
  const questions: Question[] = [];

  data.forEach((q) => {
    const rawDiff = q.difficulty ?? (q.questionNumber <= 15 ? 1 : q.questionNumber <= 35 ? 3 : 4);
    const difficultyStr: "easy" | "medium" | "hard" =
      rawDiff <= 2 ? "easy" : rawDiff === 3 ? "medium" : "hard";

    questions.push({
      id: `${testId}_q_${q.questionNumber.toString().padStart(2, "0")}`,
      questionId: q.questionId || `${testId}_q_${q.questionNumber.toString().padStart(2, "0")}`,
      conceptId: q.conceptId,
      subjectId,
      questionNumber: q.questionNumber,
      prompt: q.questionText,
      chapter: q.chapter,
      options: q.options.map((opt) => ({
        id: opt.id,
        text: opt.text,
        isCorrect: opt.isCorrect,
        misconception: opt.misconception,
        studentSelectionTrap: opt.studentSelectionTrap,
        mistakeAnalysis: opt.mistakeAnalysis,
      })),
      correctOptionId: q.correctOption,
      explanation: q.detailedSolution,
      solution: q.solution || {
        quick: `Correct option is ${q.correctOption}.`,
        concept: q.chapter ? `Principles of ${q.chapter} (${q.topic})` : "Standard NCERT Principle",
        detailed: q.detailedSolution,
      },
      topic: q.topic,
      difficulty: difficultyStr,
      difficultyLevel: (rawDiff >= 1 && rawDiff <= 5 ? rawDiff : 3) as 1 | 2 | 3 | 4 | 5,
      questionType: q.questionType || "conceptual",
      estimatedTimeSeconds: q.estimatedTimeSeconds || 60,
      formula: q.formula,
      keyConcept: q.keyConcept,
      tags: q.tags || [subjectId, q.chapter, q.topic],
      qualityScore: q.qualityScore || 95,
      hasDiagram: q.hasDiagram || false,
      diagramDescription: q.diagramDescription || null,
      pyqSource: sourceLabel,
      aiDiagnosisNotes: `${notesPrefix}: ${q.chapter} - ${q.topic}. Common error trap: ${
        q.options.find((opt) => opt.isCorrect === false)?.studentSelectionTrap || "See detailed solution"
      }`,
    });
  });

  return questions;
}

